#!/usr/bin/env node
// Turns a browser-storage export of the OLD MyCellar page into SQL for one user.
// The old page kept everything in localStorage:  cellar-drinks-v4, cellar-locations-v2, cellar-scale-v1.
// In the old page's browser console run:
//   copy(JSON.stringify({drinks: JSON.parse(localStorage.getItem('cellar-drinks-v4')),
//     locations: JSON.parse(localStorage.getItem('cellar-locations-v2')), scale: JSON.parse(localStorage.getItem('cellar-scale-v1'))}))
// save the clipboard to a file OUTSIDE any repo, then:
//   node scripts/import-local.mjs --in export.json --email you@example.com --out import/seed.sql
// The user must already be invited. Re-running replaces that user's cellar with the export (rerunnable).
// Prices (dollars in the old page) become integer cents; ids are kept.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { normaliseItems, normaliseLocations, normaliseScale } from '../src/validate.js';

const q = v => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");

export function buildSql(exp, email) {
  const drinks = (Array.isArray(exp.drinks) ? exp.drinks : []).map(({ price, ...d }) => ({
    ...d, price_cents: price === null || price === undefined || price === '' ? null : Math.round(Number(price) * 100),
  }));
  const items = drinks.length ? normaliseItems(drinks.map(drink => ({ drink }))) : [];
  const locations = exp.locations ? normaliseLocations(exp.locations).filter(l => !l.system) : null;
  const scale = exp.scale ? normaliseScale(exp.scale) : null;
  const now = Date.now();
  const u = `(SELECT id FROM users WHERE email = ${q(email.toLowerCase())})`;
  const out = ['-- generated by scripts/import-local.mjs; contains real data: keep out of git'];
  out.push(`DELETE FROM stock WHERE user_id = ${u};`, `DELETE FROM drinks WHERE user_id = ${u};`);
  for (const i of items) {
    out.push(`INSERT INTO drinks (user_id, id, version, price_cents, data, created_at, updated_at) VALUES (${u}, ${q(i.id)}, 1, ${q(i.price_cents)}, ${q(i.data)}, ${now}, ${now});`);
    for (const s of i.stock) out.push(`INSERT INTO stock (user_id, drink_id, ord, id, location, sublocation, position, quantity, date_added, status, date_finished) VALUES (${u}, ${q(i.id)}, ${s.ord}, ${q(s.id)}, ${q(s.location)}, ${q(s.sublocation)}, ${q(s.position)}, ${s.quantity}, ${q(s.date_added)}, ${q(s.status)}, ${q(s.date_finished)});`);
  }
  if (locations || scale) {
    out.push(`INSERT INTO settings (user_id, locations, scale, version, updated_at) VALUES (${u}, ${q(locations && JSON.stringify(locations))}, ${q(scale && JSON.stringify(scale))}, 1, ${now})`
      + ` ON CONFLICT(user_id) DO UPDATE SET locations = excluded.locations, scale = excluded.scale, version = settings.version + 1, updated_at = excluded.updated_at;`);
  }
  return { sql: out.join('\n') + '\n', drinkCount: items.length, stockCount: items.reduce((n, i) => n + i.stock.length, 0) };
}

if (process.argv[1] && process.argv[1].endsWith('import-local.mjs')) {
  const args = Object.fromEntries(process.argv.slice(2).reduce((a, x, i, all) => (x.startsWith('--') ? [...a, [x.slice(2), all[i + 1]]] : a), []));
  if (!args.in || !args.email) { console.error('Usage: node scripts/import-local.mjs --in <export.json> --email <address> [--out <file.sql>]'); process.exit(1); }
  const r = buildSql(JSON.parse(readFileSync(args.in, 'utf8')), args.email);
  const out = args.out || 'import/seed.sql';
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, r.sql);
  console.error(`wrote ${out}: ${r.drinkCount} drinks, ${r.stockCount} stock rows. Expect those counts in D1 after running it.`);
  // Writes = about one row per drink and stock entry plus index entries: tell the owner before a remote run.
  console.error(`approx rows written: ${r.drinkCount * 1 + r.stockCount * 2}`);
}
